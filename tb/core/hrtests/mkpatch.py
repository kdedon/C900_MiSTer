import sys
# words placed at ROM byte address base; write "<hex image offset> <hex byte>"
bell = [0x140E,0x0800,0x1000,0xA1FD,0x1400,0x3E00,0x0000,0x5DD0,0x0808,0x4DD8,0x080C,0xE802,0x69D0,0x080C,0x4DD1,0x080C,0x0C80,0xEF0D,0x54DA,0x0808,0x010B,0x0002,0x5DDA,0x0808,0x030B,0x0002,0x21A1,0x0901,0xFFFF,0x2FA1,0xE8ED,
 0x1400,0x3E00,0x0000,0x5DD0,0x0808,0x4DD8,0x080C,0xE802,0x69D0,0x080C,0x4DD1,0x080C,0x0C80,0xEF0D,0x54DA,0x0808,0x010B,0x0002,0x5DDA,0x0808,0x030B,0x0002,0x21A1,0x0901,0xFFFF,0x2FA1,0xE8ED]
def emit(base, words, out):
    for i,w in enumerate(words):
        a=(base+2*i)//2
        out.write("%05x %02x\n"%(a, w>>8))
        out.write("%05x %02x\n"%(0x4000+a, w&0xff))
mode=sys.argv[1]
out=open(sys.argv[2],'w')
if mode=='bell':
    count=int(sys.argv[3]) if len(sys.argv)>3 else 3200
    w=list(bell)
    w[16]=count; w[43]=count
    emit(0x38, w+[0xE8FF], out)
